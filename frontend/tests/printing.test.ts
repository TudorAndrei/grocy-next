import { expect, test, vi } from "vitest";
import { writeApiConfig } from "@/lib/config";
import { printLabel } from "@/lib/printing";

const payload = {
  type: "recipe",
  details: { id: 2, name: "Salt & spice", nullable: null, active: true },
  tags: ["x y", "a+b"],
  items: [{ name: "A" }, { name: "B" }],
  extra: "!'()~",
};

function transport(status = 200) {
  writeApiConfig({ baseUrl: "/house", apiKey: "label-key" });

  const fetchMock = vi.fn<typeof fetch>(async (input) =>
    String(input).startsWith("/house/") ? Response.json(payload) : new Response(null, { status }),
  );

  vi.stubGlobal("fetch", fetchMock);

  return fetchMock;
}

test.each([true, "off", undefined])(
  "server label mode %s sends one authenticated API request",
  async (mode) => {
    const fetchMock = transport();
    await printLabel("/api/recipes/2/printlabel", { LABEL_PRINTER_RUN_SERVER: mode });
    expect(fetchMock).toHaveBeenCalledOnce();
    const [path, init] = fetchMock.mock.calls[0]!;
    expect(path).toBe("/house/api/recipes/2/printlabel");
    expect(new Headers(init?.headers).get("GROCY-API-KEY")).toBe("label-key");
  },
);

test.each([false, "0"])("browser label mode %s sends JSON without the API key", async (mode) => {
  const fetchMock = transport();
  await printLabel("/api/recipes/2/printlabel", {
    LABEL_PRINTER_RUN_SERVER: mode,
    LABEL_PRINTER_WEBHOOK: "http://printer.test/print",
    LABEL_PRINTER_PARAMS: { type: "custom-recipe", copies: 2 },
  });
  expect(fetchMock).toHaveBeenCalledTimes(2);
  const [path, init] = fetchMock.mock.calls[1]!;
  expect(path).toBe("http://printer.test/print");
  expect(init?.method).toBe("POST");
  expect(new Headers(init?.headers).get("Content-Type")).toBe("application/json");
  expect(new Headers(init?.headers).has("GROCY-API-KEY")).toBe(false);
  expect(JSON.parse(String(init?.body))).toEqual({ ...payload, type: "custom-recipe", copies: 2 });
});

test("browser form labels retain the pinned jQuery nested-field and escaping rules", async () => {
  const fetchMock = transport();
  await printLabel("/api/recipes/2/printlabel", {
    LABEL_PRINTER_RUN_SERVER: false,
    LABEL_PRINTER_WEBHOOK: "http://printer.test/print",
    LABEL_PRINTER_HOOK_JSON: false,
  });
  const [, init] = fetchMock.mock.calls[1]!;
  expect(new Headers(init?.headers).get("Content-Type")).toBe(
    "application/x-www-form-urlencoded; charset=UTF-8",
  );
  // Generated by $.param in the jQuery shipped with Grocy 4.5.0 (21aa5eab).
  expect(init?.body).toBe(
    "type=recipe&details%5Bid%5D=2&details%5Bname%5D=Salt+%26+spice&details%5Bnullable%5D=&details%5Bactive%5D=true&tags%5B%5D=x+y&tags%5B%5D=a%2Bb&items%5B0%5D%5Bname%5D=A&items%5B1%5D%5Bname%5D=B&extra=!'()~",
  );
});

test("failed browser label requests report the error without a second print", async () => {
  const fetchMock = transport(400);
  await expect(
    printLabel("/api/recipes/2/printlabel", {
      LABEL_PRINTER_RUN_SERVER: false,
      LABEL_PRINTER_WEBHOOK: "http://printer.test/print",
    }),
  ).rejects.toThrow("Error while executing WebHook");
  expect(fetchMock).toHaveBeenCalledTimes(2);
});
